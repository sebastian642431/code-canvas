import re
import sys

WANT = """folder folder-open file file-code file-text file-json braces settings search search-code filter plus minus x
chevron-right chevron-down refresh-cw panel-left panel-right list-tree message-circle bot git-branch eye check square copy
ellipsis-vertical locate-fixed scan maximize zoom-in zoom-out send circle-stop sparkles puzzle circle-help layout-grid
database image activity palette workflow text-search mouse-pointer-2 hand trash-2 arrow-up corner-down-left
folder-tree network waypoints code share-2 square-check eye-off unfold-vertical fold-vertical
circle-alert triangle-alert info wand-sparkles download package circle-check chart-column file-archive
arrow-left history git-graph git-commit-horizontal arrow-up-down repeat-2 book-marked pencil save arrow-right eraser""".split()

css = open(sys.argv[1], encoding="utf8").read()
codes = dict(re.findall(r'\.icon-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css))
missing = [w for w in WANT if w not in codes]
print("missing:", missing, "| icons in font:", len(codes))

lines = [
    "//! Icons from the Lucide icon font (ISC license, see assets/LUCIDE-LICENSE.txt).",
    "//! Generated by scripts/make_icons.py - do not edit by hand.",
    "",
    "#![allow(dead_code)]",
    "",
]
for w in WANT:
    if w in codes:
        name = w.upper().replace("-", "_")
        lines.append('pub const %s: &str = "\\u{%s}";' % (name, codes[w]))
open("crates/code-canvas/src/icons.rs", "w", encoding="utf8").write("\n".join(lines) + "\n")
