# Generates crates/code-canvas/src/codicons.rs from the Codicons CSS.
#
#   python scripts/make_codicons.py path/to/codicon.css
#
# Codicons are VS Code's icon set. Extensions name them in their texts
# (`$(check) Prettier`), so the app needs the same names. The font
# (crates/code-canvas/assets/codicon.ttf) and the CSS come from the
# `@vscode/codicons` npm package; the icons are CC BY 4.0, see
# assets/CODICON-LICENSE.txt.
import re
import sys

css = open(sys.argv[1], encoding="utf8").read()
found = sorted(set(re.findall(r'\.codicon-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)"', css)))
print("icons:", len(found))

lines = [
    "//! Codicons, VS Code's icon set: extensions name these icons in their texts",
    "//! (`$(check) Prettier`). Icons are CC BY 4.0, see assets/CODICON-LICENSE.txt.",
    "//! Generated by scripts/make_codicons.py - do not edit by hand.",
    "",
    "/// `(name, glyph)`, sorted by name.",
    "static TABLE: &[(&str, &str)] = &[",
]
lines += ['    ("%s", "\\u{%s}"),' % (name, code) for name, code in found]
lines += [
    "];",
    "",
    "/// The glyph of the codicon called `name`.",
    "pub fn glyph(name: &str) -> Option<&'static str> {",
    "    TABLE.binary_search_by(|(n, _)| (*n).cmp(name)).ok().map(|i| TABLE[i].1)",
    "}",
    "",
    "/// Replace every `$(name)` in `text` with its glyph (`$(sync~spin)` is the",
    "/// icon `sync`; an unknown name is dropped).",
    "pub fn render(text: &str) -> String {",
    "    let mut out = String::with_capacity(text.len());",
    "    let mut rest = text;",
    '    while let Some(at) = rest.find("$(") {',
    "        let Some(len) = rest[at..].find(')') else { break };",
    "        out.push_str(&rest[..at]);",
    "        let name = rest[at + 2..at + len].split('~').next().unwrap_or_default();",
    "        out.push_str(glyph(name).unwrap_or_default());",
    "        rest = &rest[at + len + 1..];",
    "    }",
    "    out.push_str(rest);",
    "    out",
    "}",
    "",
    "#[cfg(test)]",
    "mod tests {",
    "    use super::*;",
    "",
    "    #[test]",
    "    fn names_become_glyphs() {",
    '        let check = glyph("check").unwrap();',
    '        assert_eq!(render("$(check) Prettier"), format!("{check} Prettier"));',
    '        assert_eq!(render("$(sync~spin) Working"), format!("{} Working", glyph("sync").unwrap()));',
    '        assert_eq!(render("$(no-such-icon)x $(check"), "x $(check");',
    '        assert_eq!(render("plain"), "plain");',
    "        assert!(TABLE.windows(2).all(|w| w[0].0 < w[1].0), \"sorted, for the binary search\");",
    "    }",
    "}",
]
open("crates/code-canvas/src/codicons.rs", "w", encoding="utf8", newline="\n").write("\n".join(lines) + "\n")
